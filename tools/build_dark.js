// Builds assets/css/dark-auto.css: dark versions of the hardcoded light colours in the app's CSS.
// Run after changing colours in any listed file:  node tools/build_dark.js   (needs the npm package postcss)
// Hand-made fixes go in assets/css/dark.css (loaded after this file), not here.
const fs = require('fs'), path = require('path');
const postcss = require(process.env.POSTCSS || 'postcss');
const ROOT = path.join(__dirname, '..', 'assets', 'css');
const FILES = ['style.css', 'brand.css', 'ui.css', 'motion.css', 'easy.css', 'mobile.css', 'home.css', 'community.css', 'chat.css',
    'campaign.css', 'dm.css', 'live.css', 'rewards.css', 'sp.css', 'admin-community.css', 'admin-clips.css'];
const PRE = ':root[data-theme="dark"]';
// <style> blocks written inside app pages (public pages such as index.php stay light)
const PHP_STYLES = ['creator/notifications.php', 'creator/submit_links.php', 'creator/withdraw.php', 'creator/connect_tiktok.php',
    'creator/earnings.php', 'creator/course_intro.php', 'admin/telegram.php', 'admin/creators.php', 'admin/send.php', 'admin/links.php',
    'admin/index.php', 'admin/rewards.php', 'admin/ready_clips.php', 'includes/homescreen.php', 'includes/bonus_modal.php', 'includes/home_examples.php'];

function parse(c) {
    c = c.trim().toLowerCase();
    let m;
    if ((m = c.match(/^#([0-9a-f]{3,8})$/))) {
        let h = m[1]; if (h.length <= 4) h = h.split('').map(x => x + x).join('');
        return { r: parseInt(h.slice(0, 2), 16), g: parseInt(h.slice(2, 4), 16), b: parseInt(h.slice(4, 6), 16), a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1 };
    }
    if ((m = c.match(/^rgba?\(([^)]+)\)$/))) {
        const v = m[1].split(/[\s,\/]+/).filter(Boolean).map(parseFloat);
        return { r: v[0], g: v[1], b: v[2], a: v.length > 3 ? v[3] : 1 };
    }
    if (c === 'white' || c === '#fff') return { r: 255, g: 255, b: 255, a: 1 };
    if (c === 'black') return { r: 0, g: 0, b: 0, a: 1 };
    return null;
}
function chroma(p) { return (Math.max(p.r, p.g, p.b) - Math.min(p.r, p.g, p.b)) / 255; }
function hsl({ r, g, b }) {
    r /= 255; g /= 255; b /= 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2;
    if (mx === mn) return { h: 30, s: 0, l };
    const d = mx - mn, s = l > .5 ? d / (2 - mx - mn) : d / (mx + mn);
    let h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
    return { h: h * 60, s, l };
}
function out(h, s, l, a) {
    const f = n => { const k = (n + h / 30) % 12, x = s * Math.min(l, 1 - l); return Math.round(255 * (l - x * Math.max(-1, Math.min(k - 3, 9 - k, 1)))); };
    const [r, g, b] = [f(0), f(8), f(4)];
    return a < 1 ? `rgba(${r}, ${g}, ${b}, ${+a.toFixed(3)})` : '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('');
}
// light background -> dark surface (keep hue for tints)
function bg(c) {
    const p = parse(c); if (!p) return null; const { h, s, l } = hsl(p);
    if (l < 0.86) return null;
    const tint = chroma(p) > 0.045;
    if (!tint) return out(25, 0.17, 0.105 + (1 - l) * 0.55, p.a);   // white -> #1e1814, greys a step lighter
    return out(h, Math.min(0.45, s * 0.5), 0.14 + (1 - l) * 0.25, p.a);
}
// light border -> dark line
function line(c) {
    const p = parse(c); if (!p) return null; const { h, s, l } = hsl(p);
    if (l < 0.78) return null;
    const t = chroma(p) > 0.045;
    return out(t ? h : 25, t ? Math.min(0.35, s * 0.4) : 0.17, 0.2 + (1 - l) * 0.3, p.a);
}
// dark text -> light text (keep hue for coloured text)
function text(c) {
    const p = parse(c); if (!p) return null; const { h, s, l } = hsl(p);
    if (l >= 0.47) return null;
    if (chroma(p) > 0.12) return out(h, Math.min(0.85, s), Math.max(0.68, Math.min(0.8, 1.02 - l)), p.a);
    return out(28, 0.25, Math.max(0.62, Math.min(0.93, 1.02 - l)), p.a);
}
function swapAll(value, fn) {
    let changed = false;
    const v = value.replace(/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b/g, m => { const n = fn(m); if (n) { changed = true; return n; } return m; });
    return changed ? v : null;
}
function prefix(sel) {
    return sel.split(/,(?![^(]*\))/).map(s => {
        s = s.trim();
        if (/^:root/.test(s)) return s.replace(/^:root/, PRE);
        if (/^html/.test(s)) return s.replace(/^html/, 'html[data-theme="dark"]');
        return PRE + ' ' + s;
    }).join(',\n');
}
let outCss = '/* Generated by tools/build_dark.js from the app CSS. Do not edit by hand: change dark.css instead. */\n';
let count = 0;
const SOURCES = FILES.map(f => [f, () => fs.readFileSync(path.join(ROOT, f), 'utf8')]).concat(PHP_STYLES.map(f => [f, () => {
    const src = fs.readFileSync(path.join(ROOT, '..', '..', f), 'utf8');
    return [...src.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(m => m[1].replace(/<\?(php|=)[\s\S]*?\?>/g, '0')).join('\n');
}]));
for (const [f, read] of SOURCES) {
    let root; try { root = postcss.parse(read()); } catch (e) { console.error('skip', f, e.message); continue; }
    const res = postcss.root();
    root.walkRules(rule => {
        if (rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
        if (/^(from|to|\d+%)/.test(rule.selector)) return;
        const decls = [];
        let bgSolidColoured = false;
        rule.walkDecls(/^background(-color)?$/, d => {
            (d.value.match(/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g) || []).forEach(c => { const p = parse(c); if (p && p.a > .5) { const q = hsl(p); if (q.l < 0.86 && q.l > 0.15) bgSolidColoured = true; if (q.l <= 0.15) bgSolidColoured = true; } });
        });
        rule.each(d => {
            if (d.type !== 'decl') return;
            const prop = d.prop.toLowerCase();
            let v = null;
            if (/^--/.test(prop)) return; // tokens are mapped by hand in dark.css
            if (prop === 'background' || prop === 'background-color' || prop === 'background-image') v = swapAll(d.value, bg);
            else if (/^border(-(top|right|bottom|left))?(-color)?$/.test(prop) || prop === 'outline' || prop === 'outline-color') v = swapAll(d.value, line);
            else if (prop === 'color' || prop === 'fill' || prop === '-webkit-text-fill-color') { if (!bgSolidColoured) v = swapAll(d.value, text); }
            if (v) decls.push({ prop: d.prop, value: v, important: d.important });
        });
        if (!decls.length) return;
        const r = postcss.rule({ selector: prefix(rule.selector) });
        decls.forEach(d => r.append(postcss.decl(d)));
        // keep @media / @supports wrappers
        let node = r, p = rule.parent;
        while (p && p.type === 'atrule') { if (/keyframes/i.test(p.name)) return; const a = postcss.atRule({ name: p.name, params: p.params }); a.append(node); node = a; p = p.parent; }
        res.append(node); count++;
    });
    outCss += `\n/* ---- ${f} ---- */\n` + res.toString() + '\n';
}
fs.writeFileSync(path.join(ROOT, 'dark-auto.css'), outCss);
console.log('rules', count, 'bytes', outCss.length);
